export function getEmergencyAlertTemplate(lang, village) {
  const vilName = village?.name || 'Village';
  const district = village?.district || 'District';
  const facility = village?.nearest_facility || 'CHC/PHC Hospital';

  switch (lang) {
    case 'hi':
      return `[सेतुमार्ग आपातकालीन चेतावनी] ${vilName} (${district}) हेतु चेतावनी: मुख्य संपर्क मार्ग पर भारी भूस्खलन का जोखिम/अवरोध है। ${facility} के लिए आपातकालीन चिकित्सा यात्रा समय 120 मिनट से अधिक हो गया है। ग्राम आपदा राहत सक्रिय करें। C-DoT / Exotel ग्रामीण गेटवे द्वारा प्रेषित।`;
    case 'as':
      return `[সেতুমৰ্গ জৰুৰীকালীন সতৰ্কবাৰ্তা] ${vilName} (${district}) ৰ বাবে সতৰ্কবাৰ্তা: সংযোগকাৰী পথত ভূমিস্খলনৰ উচ্চ আশংকা/অৱৰোধ আছে। ${facility} লৈ চিকিৎসা যাত্ৰাৰ সময় ১২০ মিনিটৰো অধিক হৈছে। সম্প্ৰদায়ৰ জৰুৰীকালীন খাদ্য সাহায্য সক্ৰিয় কৰক। C-DoT / Exotel গ্ৰাম্য গেটৱেৰ জৰিয়তে প্ৰেৰিত।`;
    case 'bn':
      return `[সেতুমাৰ্গ জরুরি সতর্কতা] ${vilName} (${district})-এর জন্য সতর্কতা: সংযোগ সড়কে ভারী ভূমিধসের ঝুঁকি/অবরোধ রয়েছে। ${facility}-তে জরুরি চিকিৎসার যাতায়াত সময় এখন ১২০ মিনিটের বেশি। গ্রাম পঞ্চায়েত ত্রাণ ব্যবস্থা সক্রিয় করুন। C-DoT / Exotel গ্রামীণ গেটওয়ের মাধ্যমে প্রেরিত।`;
    default:
      return `[SETUMARG URGENT] Warning for ${vilName} (${district}): Feeder road is under high landslide risk/blockage. Emergency medical transit to ${facility} currently inflated to >120m. Activate community emergency rations. SMS sent via C-DoT / Exotel rural gateway.`;
  }
}
